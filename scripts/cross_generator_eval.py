"""
Cross-Generator Generalization Evaluation Script.
Evaluates the GenAI phishing detector on phishing lures synthesized by a DIFFERENT LLM family
(out-of-distribution generator test set).
Compares against in-distribution test performance and writes results to docs/cross_generator_report.json.
Fails loudly if cross_generator_test.csv is missing. Zero synthetic sample fabrication.
"""
import sys
import os
import json
import time
from datetime import datetime, timezone
from pathlib import Path
import numpy as np
import pandas as pd
import joblib
from sklearn.metrics import (
    accuracy_score,
    precision_score,
    recall_score,
    f1_score,
    confusion_matrix
)

BASE_DIR = Path(__file__).resolve().parent.parent
if str(BASE_DIR) not in sys.path:
    sys.path.insert(0, str(BASE_DIR))

from backend.config import settings
from feature_extraction.message_features import extract_message_features_df
from feature_extraction.feature_contract import MessageFeatureContract

CROSS_GEN_FILE = BASE_DIR / "data" / "raw" / "messages" / "cross_generator_test.csv"
DOCS_DIR = BASE_DIR / "docs"
REPORT_PATH = DOCS_DIR / "cross_generator_report.json"
MODEL_PATH = settings.MODELS_DIR / "message_content" / "stylometric" / "model.joblib"
IN_DIST_META_PATH = settings.MODELS_DIR / "message_content" / "stylometric" / "metadata" / "metadata.json"

def evaluate_cross_generator_generalization():
    print("=" * 60)
    print("CROSS-GENERATOR GENERALIZATION EVALUATION")
    print("=" * 60)

    if not CROSS_GEN_FILE.exists():
        raise FileNotFoundError(
            f"Held-out cross-generator test dataset not found at: {CROSS_GEN_FILE}\n"
            f"Please place authentic phishing samples generated by alternative LLMs (e.g., Claude, LLaMA, Mistral)\n"
            f"in CSV format with 'text' and 'label' columns at this path before running."
        )

    if not MODEL_PATH.exists():
        raise FileNotFoundError(
            f"Trained message detector model not found at: {MODEL_PATH}\n"
            f"Please run `python scripts/train_message_stylometric.py` first."
        )

    df_cross = pd.read_csv(CROSS_GEN_FILE)
    text_col = "text" if "text" in df_cross.columns else df_cross.columns[0]
    label_col = "label" if "label" in df_cross.columns else ("threat_label" if "threat_label" in df_cross.columns else None)

    print(f"Loaded {len(df_cross)} cross-generator evaluation samples from: {CROSS_GEN_FILE.name}")

    # Extract features
    features_df = extract_message_features_df(df_cross[text_col].tolist())
    MessageFeatureContract.validate_and_align(features_df)

    model = joblib.load(MODEL_PATH)
    probs = model.predict_proba(features_df.values)
    preds = model.predict(features_df.values)

    report_data = {
        "timestamp": datetime.now(timezone.utc).isoformat(),
        "cross_generator_dataset": str(CROSS_GEN_FILE.name),
        "total_samples": len(df_cross),
        "metrics": {}
    }

    if label_col is not None:
        y_true = df_cross[label_col].values
        # Normalize labels if string
        if isinstance(y_true[0], str):
            mapping = {"legitimate": 0, "human_phishing": 1, "ai_phishing": 2}
            y_true = np.array([mapping.get(str(y).lower(), 1) for y in y_true])

        acc = float(accuracy_score(y_true, preds))
        macro_f1 = float(f1_score(y_true, preds, average="macro", zero_division=0))
        cm = confusion_matrix(y_true, preds).tolist()

        report_data["metrics"] = {
            "accuracy": round(acc, 4),
            "macro_f1": round(macro_f1, 4),
            "confusion_matrix": cm
        }
        print(f"\nCross-Generator Evaluation Results:")
        print(f"  Accuracy: {acc:.4f}")
        print(f"  Macro-F1: {macro_f1:.4f}")
    else:
        # Threat detection proportion
        threat_count = sum(1 for p in preds if p != 0)
        report_data["metrics"] = {
            "flagged_threat_proportion": round(threat_count / len(df_cross), 4)
        }

    # Load in-distribution baseline for comparison if available
    if IN_DIST_META_PATH.exists():
        with open(IN_DIST_META_PATH, "r") as f:
            in_dist_meta = json.load(f)
            report_data["in_distribution_comparison"] = in_dist_meta.get("champion_metrics", {})

    DOCS_DIR.mkdir(parents=True, exist_ok=True)
    with open(REPORT_PATH, "w") as f:
        json.dump(report_data, f, indent=2)

    print(f"\nCross-generator evaluation report successfully written to: {REPORT_PATH}")
    print("=" * 60)

if __name__ == "__main__":
    evaluate_cross_generator_generalization()
